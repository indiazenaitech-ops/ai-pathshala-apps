  /* Dravidian 0-99 are built from units + tens with each language's joining (sandhi) rules. */
  function build(units, teens, tens, join) {
    var a = units.slice(0, 11).concat(teens);          // 0..19
    for (var t = 2; t <= 9; t++) {
      a[t * 10] = tens[t];
      for (var u = 1; u <= 9; u++) a[t * 10 + u] = join(tens[t], units[u], t);
    }
    return a;
  }
