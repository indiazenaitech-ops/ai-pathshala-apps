#!/usr/bin/env node
/* Builds catalog.js (window.EDU_CATALOG) + APPS.md from apps/<slug>/meta.json.
   node tools/build_catalog.js [--zip <url>] [--only-passing]
   --only-passing: include only apps whose tools/reports/<slug>.json has ok:true */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const argv = process.argv.slice(2);
const zipIdx = argv.indexOf('--zip');
const zip = zipIdx >= 0 ? argv[zipIdx + 1] : '';
const onlyPassing = argv.includes('--only-passing');
const CATS = ['learn-ai', 'teacher-tools', 'math', 'science', 'coding', 'languages', 'study-skills', 'digital-safety'];
const apps = [], skipped = [];
for (const slug of fs.readdirSync(path.join(ROOT, 'apps')).sort()) {
  if (slug.startsWith('_')) continue;
  const dir = path.join(ROOT, 'apps', slug);
  const mp = path.join(dir, 'meta.json');
  if (!fs.existsSync(mp) || !fs.existsSync(path.join(dir, 'index.html'))) { skipped.push(slug + ' (incomplete)'); continue; }
  if (onlyPassing) {
    const rp = path.join(__dirname, 'reports', slug + '.json');
    const ok = fs.existsSync(rp) && JSON.parse(fs.readFileSync(rp, 'utf8')).ok;
    if (!ok) { skipped.push(slug + ' (verify not passing)'); continue; }
  }
  const m = JSON.parse(fs.readFileSync(mp, 'utf8'));
  apps.push({ slug: m.slug, icon: m.icon, category: m.category, grades: m.grades, audience: m.audience, needs: m.needs || [], tags: m.tags || [], order: m.order, title: m.title, desc: m.desc });
}
apps.sort((a, b) => CATS.indexOf(a.category) - CATS.indexOf(b.category) || a.title.en.localeCompare(b.title.en));
let out = '/* generated by tools/build_catalog.js — do not edit */\n';
out += 'window.EDU_CATALOG = ' + JSON.stringify(apps, null, 1) + ';\n';
if (zip) out += 'window.EDU_SITE = ' + JSON.stringify({ zip }) + ';\n';
fs.writeFileSync(path.join(ROOT, 'catalog.js'), out);
console.log(`catalog.js: ${apps.length} apps` + (skipped.length ? `; skipped: ${skipped.join(', ')}` : ''));
const rows = apps.map(a => `| ${a.icon} | [${a.title.en}](apps/${a.slug}/index.html) | ${a.category} | ${a.grades} | ${a.desc.en.replace(/\|/g, '/')} |`);
fs.writeFileSync(path.join(ROOT, 'APPS.md'), `# App list (${apps.length})\n\n| | App | Category | Classes | What it does |\n|---|---|---|---|---|\n${rows.join('\n')}\n`);
