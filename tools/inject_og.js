#!/usr/bin/env node
/* Adds (or refreshes) a social-sharing block in each app's index.html, built from apps/<slug>/meta.json:
   canonical URL, description, Open Graph + Twitter card tags. So a WhatsApp/Facebook/X share of an app link shows
   the app's name (English + Hindi), its one-line description and a 1200x630 image.

     node tools/inject_og.js                      dry run: prints what would change, writes nothing
     node tools/inject_og.js --write              apply to every app that has meta.json + index.html
     node tools/inject_og.js --write --only quiz-maker,flashcards
     node tools/inject_og.js --check              exit 1 if any app's block is missing or stale (for CI)

   Image: shared/img/og/<slug>.png when it exists (make it with `node tools/make_og.js --apps`), else the library
   image shared/img/og-home.png. The block sits between <!-- og:start ... --> and <!-- og:end --> right before
   </head>; running again replaces only that block. A <meta name="description"> that the app already has outside
   the block is left alone (the block then skips its own description tag).
   NOTE: this edits apps/<slug>/index.html, which app builders own. Run it only when no app agent is editing, then run
   `node tools/verify.js <slug> --quick` for the changed apps so the publish step sees a fresh PASS. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(process.env.EDU_ROOT || path.join(__dirname, '..'));   /* EDU_ROOT: test on a copy */
const SITE_URL = 'https://apnipathshala.ai/';
const argv = process.argv.slice(2);
const WRITE = argv.includes('--write'), CHECK = argv.includes('--check');
const oi = argv.indexOf('--only');
const ONLY = oi >= 0 ? (argv[oi + 1] || '').split(',').filter(Boolean) : [];
const START = '<!-- og:start (generated by tools/inject_og.js from meta.json; do not edit by hand) -->';
const END = '<!-- og:end -->';
const BLOCK_RE = /[ \t]*<!-- og:start[^>]*-->[\s\S]*?<!-- og:end -->\r?\n?/;
const attr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const clip = (s, n) => { s = String(s || '').replace(/\s+/g, ' ').trim(); return s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…' : s; };

function block(m, html) {
  const url = `${SITE_URL}apps/${m.slug}/`;
  const en = (m.title && m.title.en) || m.slug, hi = (m.title && m.title.hi) || '';
  const title = hi && hi !== en ? `${en} · ${hi} | AI Pathshala` : `${en} | AI Pathshala`;
  const desc = clip([(m.desc && m.desc.en) || '', (m.desc && m.desc.hi) || ''].filter(Boolean).join(' · '), 280);
  const ogDesc = clip(((m.desc && m.desc.en) || '') + ' Free, no sign-up, no ads, 12 Indian languages.', 300);
  const img = fs.existsSync(path.join(ROOT, 'shared', 'img', 'og', m.slug + '.png')) ? `${SITE_URL}shared/img/og/${m.slug}.png` : `${SITE_URL}shared/img/og-home.png`;
  const outside = html.replace(BLOCK_RE, '');
  const lines = [
    START,
    `<link rel="canonical" href="${url}">`,
    /<meta[^>]+name=["']description["']/i.test(outside) ? null : `<meta name="description" content="${attr(desc)}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="AI की पाठशाला · AI Pathshala">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${attr(title)}">`,
    `<meta property="og:description" content="${attr(ogDesc)}">`,
    `<meta property="og:image" content="${img}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:locale" content="en_IN">`,
    `<meta property="og:locale:alternate" content="hi_IN">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${attr(title)}">`,
    `<meta name="twitter:description" content="${attr(ogDesc)}">`,
    `<meta name="twitter:image" content="${img}">`,
    END
  ].filter(Boolean);
  return lines.map(l => '  ' + l).join('\n') + '\n';
}

let changed = 0, stale = 0, seen = 0;
for (const slug of fs.readdirSync(path.join(ROOT, 'apps')).sort()) {
  if (slug.startsWith('_') || (ONLY.length && !ONLY.includes(slug))) continue;
  const dir = path.join(ROOT, 'apps', slug), mp = path.join(dir, 'meta.json'), ip = path.join(dir, 'index.html');
  if (!fs.existsSync(mp) || !fs.existsSync(ip)) continue;
  let m; try { m = JSON.parse(fs.readFileSync(mp, 'utf8')); } catch (e) { console.log(`${slug}: bad meta.json, skipped`); continue; }
  seen++;
  const html = fs.readFileSync(ip, 'utf8');
  if (!/<\/head>/i.test(html)) { console.log(`${slug}: no </head>, skipped`); continue; }
  const b = block(m, html);
  /* function replacers: a '$' in a title or description must never be read as a replacement pattern */
  const next = BLOCK_RE.test(html) ? html.replace(BLOCK_RE, () => b) : html.replace(/([ \t]*)<\/head>/i, (m0, ind) => b + ind + '</head>');
  if (next === html) continue;
  stale++;
  if (WRITE) { const tmp = ip + '.tmp'; fs.writeFileSync(tmp, next); fs.renameSync(tmp, ip); changed++; console.log(`${slug}: OG block ${BLOCK_RE.test(html) ? 'refreshed' : 'added'}`); }
  else console.log(`${slug}: would ${BLOCK_RE.test(html) ? 'refresh' : 'add'} OG block`);
}
console.log(`${seen} apps checked, ${stale} need an update` + (WRITE ? `, ${changed} written` : ' (dry run; use --write to apply)'));
if (CHECK && stale) process.exit(1);
