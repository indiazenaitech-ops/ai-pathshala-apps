#!/usr/bin/env node
/* Language pages for search engines: one static address per language for the home page and every published app.
 *   node tools/build_lang_pages.js          writes <lang>/index.html and <lang>/apps/<slug>/index.html for the 11 non-English languages
 *   node tools/build_lang_pages.js --clean  removes the generated folders first
 * Each page is a copy of the English page with: <html lang/dir>, a title and description in that language (meta.json /
 * HOME_STRINGS), canonical = itself, hreflang links to all 12 versions (+ x-default = English), localized Open Graph and
 * JSON-LD, window.EDU_PAGE_LANG (shared/edu.js then opens the page in that language) and window.EDU_LANG_URLS (the language
 * picker goes to the matching page). Relative links/scripts are re-pointed at the original files, so the app code is not
 * copied. The English pages carry the same hreflang links (tools/inject_og.js for apps, tools/build_catalog.js for home).
 * Run after tools/build_catalog.js (publish.sh does both). Generated files: never edit by hand. */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://apnipathshala.ai/';
const LANGS = ['en', 'hi', 'bn', 'mr', 'gu', 'pa', 'or', 'ta', 'te', 'kn', 'ml', 'ur'];
const OTHER = LANGS.filter(l => l !== 'en');
const LOCALE = { en: 'en_IN', hi: 'hi_IN', bn: 'bn_IN', mr: 'mr_IN', gu: 'gu_IN', pa: 'pa_IN', or: 'or_IN', ta: 'ta_IN', te: 'te_IN', kn: 'kn_IN', ml: 'ml_IN', ur: 'ur_IN' };
const WORK = { business: 'BusinessApplication', marketing: 'BusinessApplication', everyday: 'UtilitiesApplication', data: 'BusinessApplication' };
const GEN = '<!-- generated by tools/build_lang_pages.js: do not edit -->';

const load = (file, global) => { const sb = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(ROOT, file), 'utf8'), sb); return sb.window[global]; };
const apps = load('catalog.js', 'EDU_CATALOG');
const HOME = load('shared/home-strings.js', 'HOME_STRINGS');
const brandOf = (() => {   /* COMMON.brand per language from shared/edu.js */
  const src = fs.readFileSync(path.join(ROOT, 'shared', 'edu.js'), 'utf8'); const out = {};
  for (const l of LANGS) { const m = src.match(new RegExp('^\\s+' + l + ": \\{ library: '[^']*', brand: '([^']*)'", 'm')); out[l] = m ? m[1] : 'AI Pathshala'; }
  return out;
})();
const esc = s => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const json = o => JSON.stringify(o).replace(/</g, '\\u003c');
const isRel = u => u && !/^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#|data:|mailto:|javascript:)/i.test(u);

/* hreflang + the picker's URL map for a page that exists at enPath (English) and <lang>/enPath */
function langLinks(enPath) {
  const url = l => SITE + (l === 'en' ? '' : l + '/') + enPath;
  return {
    tags: LANGS.map(l => `<link rel="alternate" hreflang="${l}" href="${url(l)}">`).concat(`<link rel="alternate" hreflang="x-default" href="${url('en')}">`),
    map: Object.fromEntries(LANGS.map(l => [l, url(l)])),
    url
  };
}

/* strip the English head blocks we replace, re-point relative URLs, set lang/dir, insert the new head block */
function localize(html, l, prefix, headLines, title) {
  let h = html
    .replace(/[ \t]*<!-- og:start[^>]*-->[\s\S]*?<!-- og:end -->\r?\n?/, '')
    .replace(/[ \t]*<link rel="canonical"[^>]*>\r?\n?/g, '')
    .replace(/[ \t]*<link rel="alternate" hreflang[^>]*>\r?\n?/g, '')
    .replace(/[ \t]*<meta (?:name|property)="(?:description|og:[^"]*|twitter:[^"]*)"[^>]*>\r?\n?/g, '')
    .replace(/[ \t]*<script type="application\/ld\+json">[\s\S]*?<\/script>\r?\n?/g, '')
    .replace(/[ \t]*<script>window\.EDU_LANG_URLS[\s\S]*?<\/script>\r?\n?/g, '')
    .replace(/<html[^>]*>/i, `<html lang="${l}" dir="${l === 'ur' ? 'rtl' : 'ltr'}">`)
    .replace(/<title>[\s\S]*?<\/title>/i, `<title>${esc(title)}</title>`)
    .replace(/(\s(?:src|href)=")([^"]*)(")/g, (m, a, u, b) => isRel(u) ? a + prefix + u + b : m);
  h = h.replace(/(<title>[\s\S]*?<\/title>)/i, (m) => m + '\n  ' + GEN + '\n' + headLines.map(x => '  ' + x).join('\n'));
  return h;
}

function writeFile(rel, content) {
  const f = path.join(ROOT, rel); fs.mkdirSync(path.dirname(f), { recursive: true });
  let old = null; try { old = fs.readFileSync(f, 'utf8'); } catch (e) { }
  if (old !== content) { fs.writeFileSync(f, content); return 1; }
  return 0;
}

if (process.argv.includes('--clean')) for (const l of OTHER) fs.rmSync(path.join(ROOT, l), { recursive: true, force: true });

let written = 0, pages = 0;
/* ---------- apps ---------- */
for (const a of apps) {
  const srcFile = path.join(ROOT, 'apps', a.slug, 'index.html');
  if (!fs.existsSync(srcFile)) continue;
  const src = fs.readFileSync(srcFile, 'utf8');
  const L = langLinks(`apps/${a.slug}/`);
  for (const l of OTHER) {
    const name = (a.title && a.title[l]) || a.title.en, desc = (a.desc && a.desc[l]) || a.desc.en;
    const title = `${name} · ${brandOf[l]}`;
    const img = SITE + 'shared/img/og-everyone-en.png';
    const ld = { '@context': 'https://schema.org', '@type': 'WebApplication', name, alternateName: a.title.en, url: L.url(l), description: desc, image: img,
      applicationCategory: WORK[a.category] || 'EducationalApplication', operatingSystem: 'Any (web browser)', isAccessibleForFree: true, inLanguage: l,
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'INR' }, publisher: { '@type': 'Organization', name: 'AI Pathshala', url: SITE } };
    const crumbs = { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: brandOf[l], item: SITE + l + '/' }, { '@type': 'ListItem', position: 2, name, item: L.url(l) }] };
    const head = [
      `<meta name="description" content="${esc(desc)}">`,
      `<link rel="canonical" href="${L.url(l)}">`, ...L.tags,
      `<meta property="og:type" content="website">`, `<meta property="og:site_name" content="${esc(brandOf[l])}">`,
      `<meta property="og:url" content="${L.url(l)}">`, `<meta property="og:title" content="${esc(title)}">`,
      `<meta property="og:description" content="${esc(desc)}">`, `<meta property="og:image" content="${img}">`,
      `<meta property="og:locale" content="${LOCALE[l]}">`, `<meta name="twitter:card" content="summary_large_image">`,
      `<script type="application/ld+json">${json(ld)}</script>`, `<script type="application/ld+json">${json(crumbs)}</script>`,
      `<script>window.EDU_PAGE_LANG = ${json(l)}; window.EDU_LANG_URLS = ${json(L.map)};</script>`
    ];
    written += writeFile(`${l}/apps/${a.slug}/index.html`, localize(src, l, `../../../apps/${a.slug}/`, head, title)); pages++;
  }
}

/* ---------- home ---------- */
{
  const src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const L = langLinks('');
  for (const l of OTHER) {
    const S = HOME[l] || HOME.en, title = S.doc_title || HOME.en.doc_title, desc = S.doc_desc || HOME.en.doc_desc;
    const head = [
      `<meta name="description" content="${esc(desc)}">`,
      `<link rel="canonical" href="${L.url(l)}">`, ...L.tags,
      `<meta property="og:type" content="website">`, `<meta property="og:site_name" content="${esc(brandOf[l])}">`,
      `<meta property="og:url" content="${L.url(l)}">`, `<meta property="og:title" content="${esc(title)}">`,
      `<meta property="og:description" content="${esc(desc)}">`, `<meta property="og:image" content="${SITE}shared/img/og-everyone-en.png">`,
      `<meta property="og:locale" content="${LOCALE[l]}">`, `<meta name="twitter:card" content="summary_large_image">`,
      `<script>window.EDU_PAGE_LANG = ${json(l)}; window.EDU_LANG_URLS = ${json(L.map)};</script>`
    ];
    let h = localize(src, l, '../', head, title);
    /* the crawlable app grid: this language's names and descriptions, linking to this language's app pages */
    const cards = apps.map(a => `<a class="app-card" href="apps/${a.slug}/"><div class="app-name"><span class="ic" aria-hidden="true">${esc(a.icon)}</span><h3>${esc((a.title && a.title[l]) || a.title.en)}</h3></div><p>${esc((a.desc && a.desc[l]) || a.desc.en)}</p></a>`).join('\n      ');
    h = h.replace(/(<!-- build:apps-static[^>]*-->)[\s\S]*?(<!-- \/build:apps-static -->)/, (m, a, b) => a + '\n      ' + cards + '\n      ' + b);
    written += writeFile(`${l}/index.html`, h); pages++;
  }
}
console.log(`language pages: ${pages} (${written} changed) in ${OTHER.join(' ')}`);
